import SwiftUI

/// A row's own measures for content and separators.
enum ListRowLayout {
  /// 39: a Settings row with no detail, as Rex's Settings rows stand.
  static let compactHeight: CGFloat = 39
  /// 48: a setup list's row.
  static let regularHeight: CGFloat = 48
  /// 38: an Activity row.
  static let denseHeight: CGFloat = 38
}
